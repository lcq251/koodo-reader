// 简体 → 繁体（玄学词汇，供界面显示用；引擎内部保持简体与参照库一致）
const WORDS = { '谷雨': '穀雨' }
const MAP = {
  兑: '兌', 离: '離', 为: '為', 泽: '澤', 风: '風', 无: '無', 讼: '訟',
  过: '過', 济: '濟', 晋: '晉', 壮: '壯', 归: '歸', 丰: '豐', 恒: '恆', 涣: '渙',
  渐: '漸', 观: '觀', 节: '節', 损: '損', 贲: '賁', 颐: '頤', 蛊: '蠱', 剥: '剝',
  临: '臨', 复: '復', 师: '師', 谦: '謙', 随: '隨', 阴: '陰', 阳: '陽',
  门: '門', 冲: '沖', 腾: '騰', 陈: '陳', 惊: '驚', 伤: '傷', 开: '開',
  蛰: '蟄', 满: '滿', 种: '種', 处: '處', 应: '應', 亲: '親', 兽: '獸', 体: '體', 用: '用', 动: '動', 无: '無', 数: '數', 局: '局', 阴: '陰', 阳: '陽',
}
export function tradify(s) {
  let t = String(s)
  for (const [k, v] of Object.entries(WORDS)) t = t.split(k).join(v)
  return t.split('').map((c) => MAP[c] || c).join('')
}
